const { app, dialog } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { once } = require('node:events')
const { sftpFixture } = require('../test-results/sftp-fixture.cjs')
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
const deadline = setTimeout(() => { console.error('SFTP smoke timed out'); app.exit(1) }, 60_000)
app.once('quit', () => clearTimeout(deadline))
app.once('browser-window-created', (_event, window) => {
  window.webContents.once('did-finish-load', async () => {
    const evaluate = (source) => window.webContents.executeJavaScript(source)
    const wait = async (source) => {
      const until = Date.now() + 12_000
      while (!(await evaluate(source))) { if (Date.now() >= until) throw new Error(`Timed out: ${source}`); await delay(30) }
    }
    const click = (text) => evaluate(`(() => { const button = Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === ${JSON.stringify(text)}); if (!button) throw new Error('Missing button'); button.click(); })()`)
    const panel = 'aside[aria-label="文件传输 · SFTP 测试"]'
    const inPanel = (expression) => 'document.querySelector(' + JSON.stringify(panel) + ')' + expression
    const pathIs = (directory) => inPanel('?.querySelector("input")?.value === ' + JSON.stringify(directory))
    const reportDirectory = (uri) => remote.shells[0].write('\x1b]7;' + uri + '\x07')
    const toggleFollow = () => evaluate(inPanel(`?.querySelector('[role="switch"]').click()`))
    const downloadDisabled = inPanel(`?.querySelector('button[aria-label="下载 hello.txt"]')?.disabled`)
    const uploadDisabled = `Array.from(${inPanel('')}.querySelectorAll('button')).find(button => button.textContent.trim() === '上传文件').disabled`
    const originalOpen = dialog.showOpenDialog, originalSave = dialog.showSaveDialog
    let remote
    try {
      remote = await sftpFixture()
      const content = Buffer.concat([Buffer.from('SFTP 中文🚀\0'), Buffer.alloc(300_000, 213)])
      const source = path.join(process.env.NOVA_TEST_PROFILE, 'upload.bin'), destination = path.join(process.env.NOVA_TEST_PROFILE, 'download.bin')
      await fs.writeFile(source, content)
      await wait('Boolean(document.querySelector(\'button[aria-label="添加连接"]\'))')
      await wait('document.querySelector("header") && !document.querySelector("[role=dialog]")')
      assert.ok(window.isVisible() && !window.isMinimized())
      assert.equal(window.webContents.getLastWebPreferences().sandbox, true)
      await evaluate('window.__events = []; window.__progress = []; window.novaTerminal.onEvent(e => window.__events.push(e)); window.novaSftp.onProgress(e => window.__progress.push(e)); document.querySelector(\'button[aria-label="添加连接"]\').click()')
      await wait('Boolean(document.querySelector(\'[role="dialog"] form\'))')
      await evaluate(`(() => { const form = document.querySelector('[role="dialog"] form'); form.elements.name.value = 'SFTP 测试'; form.elements.host.value = '127.0.0.1'; form.elements.port.value = '${remote.port}'; form.elements.username.value = 'test'; form.elements.password.value = 'temporary'; form.requestSubmit(form.querySelector('button[value="connect"]')); })()`)
      await wait('document.body.innerText.includes("信任并连接")')
      assert.equal(remote.authCount(), 0)
      await click('信任并连接')
      await wait('window.__events.some(e => e.message?.type === "ready")')
      await click('文件传输')
      await wait(pathIs('/home/test'))
      await wait(inPanel('?.textContent.includes("等待远端 Shell 报告目录")'))
      await click('关闭')
      await wait('!' + inPanel(''))
      remote.shells[0].write('\x1b]7;file://')
      await wait('window.__events.some(e => e.message?.data?.includes("]7;file://"))')
      remote.shells[0].write('/home/test/%65mpty\x1b\\')
      await click('文件传输')
      await wait(pathIs('/home/test/empty'))
      await evaluate('document.querySelector(".xterm-helper-textarea").focus()')
      assert.ok(await evaluate('document.activeElement.classList.contains("xterm-helper-textarea")'))
      window.webContents.sendInputEvent({ type: 'char', keyCode: 'x' })
      await wait('window.__events.some(e => e.message?.type === "output" && e.message.data === "x")')

      reportDirectory('file://127.0.0.1/home/test')
      await wait(pathIs('/home/test'))
      reportDirectory('file://unrelated.invalid/home/test/empty')
      await delay(350)
      assert.ok(await evaluate(pathIs('/home/test')), 'A foreign host report must not change the directory')

      const heldDirectory = Promise.withResolvers()
      remote.holdNextDirectory(heldDirectory.promise)
      reportDirectory('file:///home/test/empty')
      const listingBusy = inPanel(`?.querySelector('[aria-label="远端文件"]').getAttribute('aria-busy')`)
      await wait(`${listingBusy} === 'true'`)
      await toggleFollow()
      heldDirectory.resolve()
      await wait(`${listingBusy} === 'false'`)
      assert.ok(await evaluate(pathIs('/home/test')), 'Pausing must discard an in-flight automatic listing')
      await toggleFollow()
      await wait(pathIs('/home/test/empty'))
      reportDirectory('file:///home/test')
      await wait(pathIs('/home/test'))

      reportDirectory('file:///missing')
      await wait(inPanel(`?.querySelector('[role="alert"]')?.textContent.includes("无法读取")`))
      assert.ok(await evaluate(downloadDisabled), 'A failed follow must not transfer from the stale listing')
      await evaluate(`(() => {
        const input = ${inPanel('')}.querySelector('input')
        Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '/home/test/empty')
        input.dispatchEvent(new Event('input', { bubbles: true }))
      })()`)
      await wait(inPanel(`?.querySelector('[role="switch"]').getAttribute('aria-checked') === 'false'`))
      assert.ok(await evaluate(`${uploadDisabled} && ${downloadDisabled}`), 'A path edit must not enable transfers from the stale listing')
      await click('打开')
      await wait(`!(${uploadDisabled}) && ${inPanel('?.textContent.includes("目录为空")')}`)
      reportDirectory('file:///home/test')
      await toggleFollow()
      await wait(`${downloadDisabled} === false`)

      await click('empty')
      await wait(pathIs('/home/test/empty'))
      assert.equal(await evaluate(inPanel(`?.querySelector('[role="switch"]')?.getAttribute("aria-checked")`)), 'false')
      reportDirectory('file:///home')
      await delay(350)
      assert.ok(await evaluate(pathIs('/home/test/empty')), 'Manual browsing must pause following')
      await click('上级目录')
      await wait(pathIs('/home/test'))
      await toggleFollow()
      await wait(pathIs('/home'))
      reportDirectory('file:///home/test')
      await wait(pathIs('/home/test'))
      dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] })
      await click('上传文件')
      await wait(inPanel('?.textContent.includes("已取消文件选择")'))
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [source] })
      await click('上传文件')
      await wait(inPanel('?.textContent.includes("上传完成")'))
      assert.deepEqual(remote.files.get('/home/test/upload.bin'), content)
      await wait(inPanel(`?.querySelector('button[aria-label="下载 upload.bin"]')?.disabled === false`))
      dialog.showSaveDialog = async (_window, options) => { assert.equal(options.defaultPath, 'upload.bin'); return { canceled: false, filePath: destination } }
      await evaluate('document.querySelector(\'button[aria-label="下载 upload.bin"]\').click()')
      await wait(inPanel('?.textContent.includes("下载完成")'))
      assert.deepEqual(await fs.readFile(destination), content)
      assert.ok(await evaluate('window.__progress.some(e => e.transferred === e.total && e.total > 0)'))
      assert.equal(await evaluate('document.querySelector(\'[role="progressbar"]\').getAttribute("aria-valuenow")'), '100')
      await fs.mkdir(path.join(__dirname, '../test-results'), { recursive: true })
      await fs.writeFile(path.join(__dirname, '../test-results/sftp-light.png'), (await window.webContents.capturePage()).toPNG())
      await evaluate(`document.querySelector('button[aria-label="切换深色主题"]')?.click()`)
      await wait('document.documentElement.classList.contains("dark")')
      window.setSize(760, 600); await delay(200)
      await fs.writeFile(path.join(__dirname, '../test-results/sftp-dark-small.png'), (await window.webContents.capturePage()).toPNG())
      assert.ok(await evaluate(inPanel('.getBoundingClientRect().right <= innerWidth')))
      await click('上传文件')
      await wait('document.querySelector(\'[role="alert"]\')?.textContent.includes("上传失败")')
      assert.deepEqual(remote.files.get('/home/test/upload.bin'), content)
      remote.files.set('/home/test/slow.bin', Buffer.alloc(1_000_000, 7)); remote.slow(true)
      await click('刷新')
      await wait('Boolean(document.querySelector(\'button[aria-label="下载 slow.bin"]\'))')
      const cancelled = path.join(process.env.NOVA_TEST_PROFILE, 'cancelled.bin')
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: cancelled })
      await evaluate('document.querySelector(\'button[aria-label="下载 slow.bin"]\').click()')
      await wait(inPanel(`?.querySelector('[role="progressbar"]') !== null`))
      reportDirectory('file:///home')
      reportDirectory('file:///home/test/empty')
      await delay(350)
      assert.ok(await evaluate(pathIs('/home/test')), 'Tracking must wait for the current transfer')
      await click('取消操作')
      await wait('document.querySelector(\'[role="alert"]\')?.textContent.includes("已取消")')
      assert.equal(await fs.stat(cancelled).then(() => true, () => false), false)
      assert.ok((await fs.readdir(process.env.NOVA_TEST_PROFILE)).every(name => !name.endsWith('.part')))
      await wait(pathIs('/home/test/empty'))
      await click('关闭')
      await wait('!' + inPanel(''))
      await evaluate('window.novaTerminal.send(window.__events.find(e => e.message?.type === "ready").id, {type:"input", data:"SFTP_TERMINAL_ALIVE"})')
      await wait('window.__events.some(e => e.message?.type === "output" && e.message.data.includes("SFTP_TERMINAL_ALIVE"))')
      assert.equal(remote.authCount(), 1)
      await evaluate('window.novaTerminal.close(window.__events.find(e => e.message?.type === "ready").id)')
      await wait('window.__events.some(e => e.closed)')
      await remote.close(); remote = undefined
      console.log('Desktop smoke passed: SFTP shared SSH trust, OSC 7 directory following, manual pause and deferred follow, picker cancellation, upload/download bytes, progress, collision protection, cancellation, sandbox, small dark layout and live terminal.')
      const closed = once(window, 'closed'); window.close(); await closed; app.quit()
    } catch (error) {
      console.error(error)
      if (!window.isDestroyed()) { await fs.mkdir(path.join(__dirname, '../test-results'), { recursive: true }); await fs.writeFile(path.join(__dirname, '../test-results/sftp-failure.png'), (await window.webContents.capturePage()).toPNG()) }
      await remote?.close(); app.exit(1)
    } finally { dialog.showOpenDialog = originalOpen; dialog.showSaveDialog = originalSave }
  })
})
if (process.env.NOVA_TEST_PROFILE) app.setPath('userData', process.env.NOVA_TEST_PROFILE)
require(process.argv[2] || '../out/electron/main.cjs')
